bool PersistentSave::readRecord(const char* key, Record& record) {
#if defined(ARDUINO_ARCH_ESP32)
  File file = SPIFFS.open(savePath(key), "r");
  if (!file) return false;
  const bool matches = file.size() == static_cast<size_t>(sizeof(Record)) &&
                       file.readBytes(reinterpret_cast<char*>(&record), sizeof(Record)) == sizeof(Record);
  file.close();
  return matches;
#else
  return preferences_.getBytesLength(key) == sizeof(Record) && preferences_.getBytes(key, &record, sizeof(Record)) == sizeof(Record);
#endif
}
