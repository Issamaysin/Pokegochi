// A new physical Pokegochi must not start on the same deterministic random
// stream as every other unit.  The eFuse MAC makes the stream device-specific
// while ESP32's hardware RNG and the boot timer ensure that even a deliberate
// factory reset does not replay the unit's previous game.  These values are
// written into the first redundant save record, so subsequent boots continue
// the persisted streams instead of reseeding an existing game.
void seedNewSaveRandomness(GameSave& save) {
#if defined(ARDUINO_ARCH_ESP32)
  const uint64_t mac = ESP.getEfuseMac();
  uint64_t entropy = mac ^ (static_cast<uint64_t>(esp_random()) << 32U) ^
                     static_cast<uint64_t>(esp_random()) ^
                     (static_cast<uint64_t>(micros()) << 17U);
  const auto nextSeed = [&entropy](uint64_t stream) {
    uint64_t value = (entropy += 0x9E3779B97F4A7C15ULL) ^ stream;
    value = (value ^ (value >> 30U)) * 0xBF58476D1CE4E5B9ULL;
    value = (value ^ (value >> 27U)) * 0x94D049BB133111EBULL;
    value ^= value >> 31U;
    uint32_t seed = static_cast<uint32_t>(value ^ (value >> 32U));
    return seed ? seed : static_cast<uint32_t>(stream | 1U);
  };
  save.wildEncounterClock.rngState = nextSeed(0x57494C44ULL);  // "WILD"
  save.battle.rngState = nextSeed(0x42415454ULL);              // "BATT"
  save.mart.rng = nextSeed(0x4D415254ULL);                    // "MART"
  Serial.printf("[IDENTITY] new-save MAC=%04llX%08llX RNG=%08lX/%08lX/%08lX\n",
                static_cast<unsigned long long>((mac >> 32U) & 0xFFFFU),
                static_cast<unsigned long long>(mac & 0xFFFFFFFFULL),
                static_cast<unsigned long>(save.wildEncounterClock.rngState),
                static_cast<unsigned long>(save.battle.rngState),
                static_cast<unsigned long>(save.mart.rng));
#endif
}

